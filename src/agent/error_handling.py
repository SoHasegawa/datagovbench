from src.agent.utils import execute_code


class ErrorHandlingAgent:
    def __init__(self, model="gpt4"):
        self.llm = model

    def evaluate(self, error, code):
        prompt = f"""You are a top data analyst with much experience on Python. Given the Python code and error message generated by executing the code, your task is to revise the Python code. Error message is '{error}', and the here is the Python code. Please do not include try-except statement. You should output only the code without any other text and markdown formatting:
{code}
"""

        generated_text = self.llm.generate_format(prompt, format='code')
        return generated_text

    def __call__(self, error, code):
        code = self.evaluate(error, code)
        output, error = execute_code(code)
        count = 0

        flows = {"codes": [code], "output": [output], "error": [error]}

        while error != "" and count < 3:
            code = self.evaluate(error, code)
            output, error = execute_code(code)

            flows["codes"].append(code)
            flows["output"].append(output)
            flows["error"].append(error)
            count += 1

        return code, output, flows
